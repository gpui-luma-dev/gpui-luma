// Upstream: https://github.com/radix-ui/website/blob/bb424082fd33fadc244a6dd276d3ced55caa6234/components/generate-radix-colors.tsx
// Regenerate the P3 catalog and test vectors with Node 24+ (no production JS dependency).
// Usage: node generate-custom-colors.mjs /absolute/reference-directory
// That directory must contain generate-radix-colors.ts from the revision below, and
// node_modules with @radix-ui/colors@3.0.0, colorjs.io@0.5.2, bezier-easing@2.1.0.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire, stripTypeScriptTypes} from 'node:module';
import {fileURLToPath, pathToFileURL} from 'node:url';

const directory = path.resolve(process.argv[2]);
const require = createRequire(path.join(directory, 'package.json'));
const colors = require('@radix-ui/colors');
const source = path.join(directory, 'generate-radix-colors.ts');
const modulePath = path.join(directory, 'reference.mjs');
fs.writeFileSync(modulePath, stripTypeScriptTypes(fs.readFileSync(source, 'utf8')));
const {generateRadixColors} = await import(pathToFileURL(modulePath));
const output = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/custom_colors');
const families = ['gray','mauve','slate','sage','olive','sand','tomato','red','ruby','crimson','pink','plum','purple','violet','iris','indigo','blue','cyan','teal','jade','green','grass','brown','orange','sky','mint','lime','yellow','amber'];
const number = value => Number.isInteger(value) ? `${value}.0` : `${value}`;
let catalog = '// Generated by tools/generate-custom-colors.mjs from @radix-ui/colors 3.0.0.\n// Display-P3 RGB coordinates; do not replace with clipped sRGB catalog colors.\n';
for (const appearance of ['light','dark']) {
  catalog += `pub(super) const ${appearance.toUpperCase()}: [[[f64; 3]; 12]; 29] = [\n`;
  for (const family of families) {
    catalog += `    [ // ${family}\n`;
    for (const value of Object.values(colors[family + (appearance === 'dark' ? 'Dark' : '') + 'P3'])) {
      const rgb = value.match(/display-p3 ([^)]+)/)[1].split(' ').map(Number);
      catalog += `        [${rgb.map(number).join(', ')}],\n`;
    }
    catalog += '    ],\n';
  }
  catalog += '];\n';
}
fs.writeFileSync(path.join(output,'catalog.rs'),catalog);
const seeds = [
  ['cayenne', '#941100', '#8b8d98'],
  ['indigo', '#3e63dd', '#8b8d98'],
  ['desaturated_blue', '#6c7b91', '#888888'],
  ['yellow', '#ffff00', '#8d8870'],
  ['cyan', '#00ffff', '#6f8d88'],
  ['magenta', '#ff00ff', '#998089'],
  ['black', '#000000', '#888888'],
  ['white', '#ffffff', '#888888'],
  ['near_black', '#010101', '#111113'],
  ['neutral', '#808080', '#000000'],
];
let fixtures = '// Generated by tools/generate-custom-colors.mjs using the upstream Radix generator.\n// Input hex, expected accent/gray 12-step sRGB and contrast; never computed by Rust.\nconst CASES: &[Fixture] = &[\n';
for (const appearance of ['light','dark']) {
  for (const [name,accent,gray] of seeds) {
    for (const background of appearance === 'light' ? ['#ffffff','#f0e5d8'] : ['#000000','#111113','#292433']) {
      const result = generateRadixColors({appearance, accent, gray, background});
      const u32 = hex => '0x' + (hex.length === 4 ? [...hex.slice(1)].map(c=>c+c).join('') : hex.slice(1));
      fixtures += `    Fixture { name: "${name}", mode: ThemeMode::${appearance === 'light' ? 'Light' : 'Dark'}, inputs: [${[accent,gray,background].map(u32)}], accent: [${result.accentScale.map(u32)}], gray: [${result.grayScale.map(u32)}], contrast: ${u32(result.accentContrast)} },\n`;
    }
  }
}
fixtures += '];\n';
fs.writeFileSync(path.join(output,'fixtures.rs'),fixtures);
